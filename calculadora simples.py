# --- Desafio: Calculo Simples ---
print("\n--- Calculadora Básica ---")

num1 = float(input("Digite o primeiro número: "))
num2 = float(input("Digite o segundo número: "))

soma = num1 + num2
subtracao = num1 - num2
multiplacacao = num1 * num2

print(f"Soma: {num1} + {num2} = {soma}")
print(f"Subtracao: {num1} - {num2} = {subtracao}")
print(f"Multiplicacao: {num1} * {num2} = {multiplacacao}")